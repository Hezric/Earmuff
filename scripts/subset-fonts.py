from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
out = root / 'public/fonts'
out.mkdir(parents=True, exist_ok=True)
chars = {ord(c) for c in (root / 'src/state.js').read_text(encoding='utf-8') if 0x3000 <= ord(c) <= 0x9FFF}
covered = set()
css = ['/* Generated by scripts/subset-fonts.py from the bundled UI strings. */']
for source in sorted((root / 'node_modules/@fontsource-variable/noto-sans-sc/files').glob('*.woff2')):
    font = TTFont(source)
    keep = chars.intersection(font.getBestCmap()) - covered
    if not keep:
        font.close()
        continue
    options = subset.Options()
    options.flavor = 'woff2'
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=keep)
    worker.subset(font)
    target = f'noto-sc-{len(css):02}.woff2'
    font.flavor = 'woff2'
    font.save(out / target)
    font.close()
    css.append("@font-face{font-family:'Noto Sans SC';font-style:normal;font-weight:100 900;font-display:block;src:url('/fonts/" + target + "') format('woff2');unicode-range:" + ','.join(f'U+{c:X}' for c in sorted(keep)) + ';}')
    covered.update(keep)
assert chars == covered, f'Missing UI glyphs: {chars - covered}'
(out / 'noto-ui.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
print(f'Subset {len(covered)} UI glyphs into {len(css)-1} WOFF2 files')
